SOURCE_TYPE = "project_authored_synthetic"
GENERATION_METHOD = "curated_semantic_composition"
REVIEW_STATUS = "agent_reviewed_pending_project_review"
RIGHTS_STATUS = "project_controlled_no_third_party_text"


@dataclass(frozen=True)
class FamilySpec:
    name: str
    split: str
    users: tuple[str, ...]
    replies: tuple[str, ...]
    label: str
    safety_critical: bool = False


def _family_rows(spec: FamilySpec) -> list[GreetingExample]:
    rows: list[GreetingExample] = []
    template = f"template:{spec.name}"
    batch = f"project-batch-{spec.split}-v1"
    group = f"{spec.name}|{template}|{batch}|{SOURCE_TYPE}"
    for index, (user, reply) in enumerate(product(spec.users, spec.replies), 1):
        rows.append(
            GreetingExample(
                source_id=f"r34a1-{spec.name}-{index:04d}",
                user=user,
                reply=reply,
                label=spec.label,
                source_type=SOURCE_TYPE,
                generation_method=GENERATION_METHOD,
                scenario_family=spec.name,
                prompt_template=template,
                generation_batch=batch,
                review_status=REVIEW_STATUS,
                rights_status=RIGHTS_STATUS,
                split_group=group,
                assigned_split=spec.split,
                safety_critical=spec.safety_critical,
            )
        )
    return rows



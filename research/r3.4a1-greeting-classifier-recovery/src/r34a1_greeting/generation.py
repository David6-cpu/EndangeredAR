def build_project_corpus() -> list[GreetingExample]:
    rows: list[GreetingExample] = []
    for spec in (*_positive_specs(), *_ordinary_specs(), *_state_specs(), *_hard_specs()):
        rows.extend(_family_rows(spec))
    seen: set[str] = set()
    unique: list[GreetingExample] = []
    for row in rows:
        key = normalized_pair(row)
        if key in seen:
            continue
        seen.add(key)
        unique.append(row)
    return unique


